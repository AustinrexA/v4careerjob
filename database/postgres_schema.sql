
-- V4Career PostgreSQL schema
-- Creates tables only. Does not delete existing data.
-- Run against the empty Neon v4career database.

CREATE TABLE IF NOT EXISTS sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    base_url VARCHAR(2048) NOT NULL,
    source_type VARCHAR(50) NOT NULL DEFAULT 'job_website',
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sources_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    external_id VARCHAR(255),
    url_hash CHAR(64) NOT NULL,
    title VARCHAR(500) NOT NULL,
    company VARCHAR(255),
    location VARCHAR(255),
    experience VARCHAR(255),
    salary_min NUMERIC(15,2),
    salary_max NUMERIC(15,2),
    salary_currency CHAR(3) NOT NULL DEFAULT 'INR',
    salary_period VARCHAR(12) NOT NULL DEFAULT 'year',
    skills JSONB,
    description TEXT,
    job_url VARCHAR(2048) NOT NULL,
    posted_at TIMESTAMP,
    first_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'unknown',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_jobs_source_url UNIQUE (source_id, url_hash),
    CONSTRAINT uq_jobs_source_external_id UNIQUE (source_id, external_id),
    CONSTRAINT fk_jobs_source
        FOREIGN KEY (source_id) REFERENCES sources(id)
);

CREATE TABLE IF NOT EXISTS collection_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'running',
    records_found INTEGER NOT NULL DEFAULT 0,
    records_inserted INTEGER NOT NULL DEFAULT 0,
    records_updated INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,

    CONSTRAINT fk_runs_source
        FOREIGN KEY (source_id) REFERENCES sources(id)
);

CREATE INDEX IF NOT EXISTS idx_jobs_title
    ON jobs (title);

CREATE INDEX IF NOT EXISTS idx_jobs_company
    ON jobs (company);

CREATE INDEX IF NOT EXISTS idx_jobs_location
    ON jobs (location);

CREATE INDEX IF NOT EXISTS idx_jobs_status
    ON jobs (status);

CREATE INDEX IF NOT EXISTS idx_jobs_posted_at
    ON jobs (posted_at);

CREATE INDEX IF NOT EXISTS idx_jobs_salary_filter
    ON jobs (salary_currency, salary_period, salary_min, salary_max);

CREATE INDEX IF NOT EXISTS idx_jobs_created_at
    ON jobs (created_at);

CREATE INDEX IF NOT EXISTS idx_runs_source_started
    ON collection_runs (source_id, started_at);

CREATE INDEX IF NOT EXISTS idx_collection_runs_started_at
    ON collection_runs (started_at);
